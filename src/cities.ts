function norm(s: string): string {
  return s.toLowerCase().replace(/ё/g, 'е').trim();
}

export interface CityMatch {
  name: string;
  lat: number;
  lng: number;
}

export function searchCities(query: string, limit = 6): CityMatch[] {
  const q = norm(query);
  if (q.length < 2) return [];
  const starts: CityMatch[] = [];
  const contains: CityMatch[] = [];
  for (const [name, en, lat, lng] of CITIES) {
    const n = norm(name);
    const e = norm(en);
    if (n.startsWith(q) || e.startsWith(q)) starts.push({ name, lat, lng });
    else if (n.includes(q) || e.includes(q)) contains.push({ name, lat, lng });
  }
  return [...starts, ...contains].slice(0, limit);
}
